// supabaseLikePlatform is a hand-written, trimmed imitation of what a
// hosting platform such as Supabase puts into every database (schemas,
// roles, extensions in their own schema, an event trigger, a publication,
// default privileges and settings), with the application's objects on top,
// created by the application's role. ADMIN, STORAGE, ANON, AUTH and APP
// stand for the roles.
const supabaseLikePlatform = `
	set role ADMIN;
	create schema extensions;
	grant usage on schema extensions to STORAGE, ANON, AUTH, APP;
	create extension pgcrypto with schema extensions;
	create extension "uuid-ossp" with schema extensions;
	create extension hstore with schema public;
	create function extensions.pgrst_ddl_watch() returns event_trigger language plpgsql as $$ begin null; end $$;
	create event trigger pgrst_ddl_watch on ddl_command_end execute function extensions.pgrst_ddl_watch();
	create publication platform_realtime;
	create schema auth;
	create table auth.users (id uuid primary key, email text, raw_user_meta_data jsonb, created_at timestamptz default now());
	create index users_email_idx on auth.users (email);
	alter table auth.users enable row level security;
	create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
	grant usage on schema auth to ANON, AUTH, APP;
	grant all on auth.users to APP;
	reset role;
	create schema storage authorization STORAGE;
	grant STORAGE to APP;
	set role STORAGE;
	create table storage.buckets (id text primary key, name text not null, public boolean default false);
	create table storage.objects (id uuid primary key default extensions.uuid_generate_v4(), bucket_id text references storage.buckets, name text, owner uuid);
	alter table storage.objects enable row level security;
	grant usage on schema storage to ANON, AUTH, APP;
	grant all on storage.buckets, storage.objects to APP;
	reset role;
	alter default privileges for role APP in schema public grant all on tables to ANON, AUTH;
	alter database DB set "app.settings.jwt_secret" = 'super-secret';
	alter database DB set "pgrst.db_schemas" = 'public';

	set role APP;
	create table public.profiles (id uuid primary key references auth.users on delete cascade, username text);
	alter table public.profiles enable row level security;
	create policy own_profile on public.profiles for select using ((select auth.uid()) = id);
	create function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
	begin
	  insert into public.profiles (id) values (new.id);
	  return new;
	end $$;
	create table public.todos (id bigint generated by default as identity primary key, user_id uuid not null references auth.users, task text, token text default extensions.uuid_generate_v4()::text);
	reset role;`

// TestIntegrationExternalSupabaseLike adopts a Supabase-like database with
// an external: block: pull writes only the application, an app-only YAML
// plans nothing for the platform's objects even with --unsafe --prune, a
// trigger, a policy and rows on platform tables are managed through
// attribute-only declarations, and what the platform adds later (grants,
// settings, policies, triggers, rows) is left alone.
func TestIntegrationExternalSupabaseLike(t *testing.T) {
	admin := connect(t)
	ctx := context.Background()
	roles := map[string]string{}
	for _, r := range []string{"plat_admin", "plat_storage", "plat_anon", "plat_auth", "plat_reader", "app"} {
		roles[r] = freshRole(t, admin, r)
	}
	for _, stmt := range []string{
		fmt.Sprintf("alter role %q superuser", roles["plat_admin"]),
		fmt.Sprintf("alter role %q login password 'pgy'", roles["app"]),
	} {
		if _, err := admin.Exec(ctx, stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
	const dbName = "pgytest_external_supabase"
	freshDatabase(t, admin, dbName)
	if _, err := admin.Exec(ctx, fmt.Sprintf("alter database %s owner to %q", dbName, roles["app"])); err != nil {
		t.Fatal(err)
	}
	platform := connectTo(t, dbName, "")
	app := connectTo(t, dbName, roles["app"])
	names := strings.NewReplacer("ADMIN", q(roles["plat_admin"]), "STORAGE", q(roles["plat_storage"]), "ANON", q(roles["plat_anon"]), "AUTH", q(roles["plat_auth"]), "APP", q(roles["app"]), "DB", dbName)
	if _, err := platform.Exec(ctx, names.Replace(supabaseLikePlatform)); err != nil {
		t.Fatal(err)
	}
	ext := &schema.External{
		Schemas:  []string{"auth", "storage", "extensions"},
		Roles:    []string{strings.TrimSuffix(roles["plat_admin"], "admin") + "*"},
		Settings: []string{"pgrst.*", "app.settings.*"},
	}

	res, err := pull.Build(introspectAll(t, app), pull.Options{Single: true, External: ext})
	if err != nil {
		t.Fatal(err)
	}
	pulled := string(res.Files[0].Content)
	for _, want := range []string{"table profiles:", "table todos:", "function handle_new_user():", "own_profile:", "for: " + roles["app"]} {
		if !strings.Contains(pulled, want) {
			t.Errorf("want %q in the pulled YAML:\n%s", want, pulled)
		}
	}
	for _, unwanted := range []string{"schema auth", "schema storage", "schema extensions", "pgcrypto", "uuid-ossp", "hstore", "pgrst_ddl_watch", "platform_realtime", "jwt_secret", "pgrst.", "eventTriggers", "publications"} {
		if strings.Contains(pulled, unwanted) {
			t.Errorf("%q belongs to the platform and must be left out:\n%s", unwanted, pulled)
		}
	}
	if len(res.Warnings) > 0 {
		t.Errorf("unexpected warnings: %v", res.Warnings)
	}

	opts := diff.Options{Unsafe: true, Prune: true, External: ext}
	if sql := planExternal(t, app, pulled, opts); sql != "" {
		t.Errorf("the app-only YAML must plan nothing for the platform's objects:\n%s", sql)
	}
	withBlocks := pulled + "extensions: []\neventTriggers: {}\npublications: {}\n"
	if sql := planExternal(t, app, withBlocks, opts); sql != "" {
		t.Errorf("empty extensions, eventTriggers and publications blocks must not prune the platform's:\n%s", sql)
	}

	managed := pulled + `
database:
  set: {work_mem: 8MB}
schema auth:
  table users:
    triggers:
      on_auth_user_created: {timing: after, events: [insert], level: row, procedure: public.handle_new_user()}
schema storage:
  table objects:
    policies:
      avatars_read: {for: select, using: "bucket_id = 'avatars'"}
  table buckets:
    data:
      key: [id]
      rows:
        - {id: avatars, name: avatars, public: true}
`
	d, err := schema.LoadAndMerge([]string{writeYAML(t, managed)})
	if err != nil {
		t.Fatal(err)
	}
	plan := diff.PlanWith(introspectWith(t, app, d, opts), d, opts)
	sql := diff.Render(plan)
	for _, want := range []string{"set work_mem = ''8MB''", `create trigger "on_auth_user_created"`, `create policy "avatars_read" on "storage"."objects"`, `insert into "storage"."buckets"`} {
		if !strings.Contains(sql, want) {
			t.Errorf("want %q in the plan:\n%s", want, sql)
		}
	}
	for _, unwanted := range []string{"drop ", "create schema", "create table", "alter table \"auth\".\"users\" drop", "users_email_idx"} {
		if strings.Contains(sql, unwanted) {
			t.Errorf("the plan must leave the platform's tables alone (%q):\n%s", unwanted, sql)
		}
	}
	if stmt, err := applyAsMigrations(ctx, app, plan); err != nil {
		t.Fatalf("%q: %v\n%s", stmt, err, sql)
	}
	if sql := planExternal(t, app, managed, opts); sql != "" {
		t.Errorf("the attribute-only declarations must converge:\n%s", sql)
	}
	var made bool
	if err := app.QueryRow(ctx, `select exists (select from pg_trigger where tgname = 'on_auth_user_created') and exists (select from storage.buckets where id = 'avatars')`).Scan(&made); err != nil || !made {
		t.Fatalf("trigger or row missing: %v", err)
	}

	if _, err := platform.Exec(ctx, names.Replace(`
		grant select on public.todos to `+q(roles["plat_reader"])+`;
		alter database DB set "pgrst.db_schemas" = 'public, graphql_public';
		set role STORAGE;
		insert into storage.buckets values ('platform', 'platform', false);
		create policy platform_service on storage.objects for all using (true);
		reset role;
		create function auth.on_change() returns trigger language plpgsql as $$ begin return new; end $$;
		create trigger platform_audit after update on auth.users for each row execute function auth.on_change();`)); err != nil {
		t.Fatal(err)
	}
	if sql := planExternal(t, app, managed, opts); sql != "" {
		t.Errorf("what the platform adds later must be left alone:\n%s", sql)
	}
	noExternal := opts
	noExternal.External = nil
	sql = planExternal(t, app, managed, noExternal)
	for _, want := range []string{`revoke select on table "public"."todos" from ` + q(roles["plat_reader"]), "reset pgrst.db_schemas", `drop policy "platform_service"`, `drop trigger "platform_audit"`} {
		if !strings.Contains(sql, want) {
			t.Errorf("without the external block %q is planned, got:\n%s", want, sql)
		}
	}
}

func q(name string) string { return `"` + strings.ReplaceAll(name, `"`, `""`) + `"` }

// connectTo connects to database name as role (the DSN's role when empty;
// the password of every other role is pgy).
func connectTo(t *testing.T, name, role string) *pgxpool.Pool {
	t.Helper()
	cfg, err := pgxpool.ParseConfig(dsn(t))
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.Database = name
	if role != "" {
		cfg.ConnConfig.User, cfg.ConnConfig.Password = role, "pgy"
	}
	pool, err := pgxpool.NewWithConfig(context.Background(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	return pool
}

// introspectWith introspects pool the way pgy diff does for d with opts.
func introspectWith(t *testing.T, pool *pgxpool.Pool, d *schema.Database, opts diff.Options) *diff.Live {
	t.Helper()
	ctx := context.Background()
	live, err := diff.Introspect(ctx, pool)
	if err != nil {
		t.Fatal(err)
	}
	if err := diff.IntrospectExtensions(ctx, pool, live, d, opts); err != nil {
		t.Fatal(err)
	}
	if err := diff.IntrospectDataWith(ctx, pool, live, d, opts); err != nil {
		t.Fatal(err)
	}
	if err := diff.ProbeExpressions(ctx, pool, live, d); err != nil {
		t.Fatal(err)
	}
	return live
}

// planExternal renders the plan for the YAML y against pool with opts.
func planExternal(t *testing.T, pool *pgxpool.Pool, y string, opts diff.Options) string {
	t.Helper()
	d, err := schema.LoadAndMerge([]string{writeYAML(t, y)})
	if err != nil {
		t.Fatalf("%v\n%s", err, y)
	}
	return strings.TrimSpace(diff.Render(diff.PlanWith(introspectWith(t, pool, d, opts), d, opts)))
}
