package diff

import (
	"strings"
	"testing"

	"github.com/suprbdev/pgy/internal/schema"
)

func identityDB() *schema.Database {
	cycle := true
	return &schema.Database{Tables: map[string]*schema.Table{"app.t": {
		Name: "t",
		Columns: map[string]*schema.Column{
			"id":  {Type: "bigint", Identity: "always", IdentityOptions: &schema.Sequence{Start: "1000", Increment: "5", Cycle: &cycle}},
			"n":   {Type: "int", Identity: "by default"},
			"ref": {Type: "int"},
		},
	}}}
}

func TestIdentityOptionsCreate(t *testing.T) {
	sql := Render(Plan(emptyLive(), identityDB(), false))
	for _, want := range []string{
		`"id" bigint not null generated always as identity (increment by 5 start with 1000 cycle)`,
		`"n" int not null generated by default as identity`,
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("missing %q in\n%s", want, sql)
		}
	}
}

func TestIdentityOptionsAlter(t *testing.T) {
	live := Simulate(emptyLive(), identityDB())
	if sql := Render(Plan(live, identityDB(), true)); sql != "" {
		t.Fatalf("simulated state must match, got:\n%s", sql)
	}
	d := identityDB()
	no := false
	d.Tables["app.t"].Columns["id"].IdentityOptions = &schema.Sequence{Start: "2000", Increment: "5", Cycle: &no, Cache: "20"}
	d.Tables["app.t"].Columns["n"].Identity = "always"
	p := Plan(live, d, false)
	for _, want := range []string{
		`alter table "app"."t" alter column "id" set start with 2000 set cache 20 set no cycle;`,
		`alter table "app"."t" alter column "n" set generated always;`,
	} {
		if !findAlter(p, want) {
			t.Errorf("missing %q in %v", want, p.Alters)
		}
	}
	d = identityDB()
	d.Tables["app.t"].Columns["n"].Identity = ""
	d.Tables["app.t"].Columns["ref"].Identity = "by default"
	d.Tables["app.t"].Columns["ref"].IdentityOptions = &schema.Sequence{Start: "500"}
	live.Tables["app.t"].Columns["ref"].Default = "0"
	if sql := Render(Plan(live, d, false)); strings.Contains(sql, "identity") {
		t.Errorf("adding or dropping an identity needs --unsafe, got:\n%s", sql)
	}
	p = Plan(live, d, true)
	for _, want := range []string{
		`alter table "app"."t" alter column "n" drop identity if exists;`,
		`alter table "app"."t" alter column "ref" drop default;`,
		`alter table "app"."t" alter column "ref" add generated by default as identity (start with 500);`,
	} {
		if !findAlter(p, want) {
			t.Errorf("missing %q in %v", want, p.Alters)
		}
	}
}

func TestIdentitySequenceGrantsCreateNoSequence(t *testing.T) {
	d := identityDB()
	d.Tables["app.t"].Columns["s"] = &schema.Column{Type: "bigserial"}
	d.Tables["app.t"].Columns["named"] = &schema.Column{Type: "bigint", Identity: "always", IdentityOptions: &schema.Sequence{Name: "named_ids"}}
	d.Sequences = map[string]*schema.Sequence{
		"app.t_n_seq":    {Grants: map[string][]string{"reader": {"usage"}}, Comment: "n ids"},
		"app.named_ids":  {Grants: map[string][]string{"reader": {"select"}}},
		"app.t_s_seq":    {Grants: map[string][]string{"reader": {"update"}}},
		"app.standalone": {},
	}
	sql := Render(Plan(emptyLive(), d, false))
	for _, seq := range []string{"t_n_seq", "named_ids", "t_s_seq"} {
		if strings.Contains(sql, `create sequence if not exists "app"."`+seq+`"`) {
			t.Errorf("the column creates %s, so the plan must not:\n%s", seq, sql)
		}
	}
	table := strings.Index(sql, `create table if not exists "app"."t"`)
	for _, want := range []string{
		`create sequence if not exists "app"."standalone";`,
		`grant usage on sequence "app"."t_n_seq" to "reader";`,
		`grant select on sequence "app"."named_ids" to "reader";`,
		`grant update on sequence "app"."t_s_seq" to "reader";`,
		`comment on sequence "app"."t_n_seq" is 'n ids';`,
	} {
		if i := strings.Index(sql, want); i < 0 || strings.HasPrefix(want, "grant") && i < table {
			t.Errorf("want %q after the table in:\n%s", want, sql)
		}
	}

	live := Simulate(emptyLive(), d)
	live.TableGrants = map[string]map[string]map[string]bool{
		"app.t_n_seq":   {"reader": {"usage": true}},
		"app.named_ids": {"reader": {"select": true}},
		"app.t_s_seq":   {"reader": {"update": true}},
	}
	live.RelComments["app.t_n_seq"] = "n ids"
	live.Tables["app.t"].Columns["s"].Default = "nextval('app.t_s_seq'::regclass)"
	if sql := Render(Plan(live, d, true)); sql != "" {
		t.Errorf("the sequences in their declared state must not diff:\n%s", sql)
	}
}
