package diff

import (
	"strings"
	"testing"

	"github.com/suprbdev/pgy/internal/schema"
)

func identityDB() *schema.Database {
	cycle := true
	return &schema.Database{Tables: map[string]*schema.Table{"app.t": {
		Name: "t",
		Columns: map[string]*schema.Column{
			"id":  {Type: "bigint", Identity: "always", IdentityOptions: &schema.Sequence{Start: "1000", Increment: "5", Cycle: &cycle}},
			"n":   {Type: "int", Identity: "by default"},
			"ref": {Type: "int"},
		},
	}}}
}

func TestIdentityOptionsCreate(t *testing.T) {
	sql := Render(Plan(emptyLive(), identityDB(), false))
	for _, want := range []string{
		`"id" bigint not null generated always as identity (increment by 5 start with 1000 cycle)`,
		`"n" int not null generated by default as identity`,
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("missing %q in\n%s", want, sql)
		}
	}
}

func TestIdentityOptionsAlter(t *testing.T) {
	live := Simulate(emptyLive(), identityDB())
	if sql := Render(Plan(live, identityDB(), true)); sql != "" {
		t.Fatalf("simulated state must match, got:\n%s", sql)
	}
	d := identityDB()
	no := false
	d.Tables["app.t"].Columns["id"].IdentityOptions = &schema.Sequence{Start: "2000", Increment: "5", Cycle: &no, Cache: "20"}
	d.Tables["app.t"].Columns["n"].Identity = "always"
	p := Plan(live, d, false)
	for _, want := range []string{
		`alter table "app"."t" alter column "id" set start with 2000 set cache 20 set no cycle;`,
		`alter table "app"."t" alter column "n" set generated always;`,
	} {
		if !findAlter(p, want) {
			t.Errorf("missing %q in %v", want, p.Alters)
		}
	}
	d = identityDB()
	d.Tables["app.t"].Columns["n"].Identity = ""
	d.Tables["app.t"].Columns["ref"].Identity = "by default"
	d.Tables["app.t"].Columns["ref"].IdentityOptions = &schema.Sequence{Start: "500"}
	live.Tables["app.t"].Columns["ref"].Default = "0"
	if sql := Render(Plan(live, d, false)); strings.Contains(sql, "identity") {
		t.Errorf("adding or dropping an identity needs --unsafe, got:\n%s", sql)
	}
	p = Plan(live, d, true)
	for _, want := range []string{
		`alter table "app"."t" alter column "n" drop identity if exists;`,
		`alter table "app"."t" alter column "ref" drop default;`,
		`alter table "app"."t" alter column "ref" add generated by default as identity (start with 500);`,
	} {
		if !findAlter(p, want) {
			t.Errorf("missing %q in %v", want, p.Alters)
		}
	}
}
